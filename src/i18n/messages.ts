export type MessageKey = keyof typeof table;

export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = vars[name];
    return value === undefined ? `{${name}}` : String(value);
  });
}

export function t(key: MessageKey, locale: Locale | string, vars?: Record<string, string | number>): string {
  const lang = parseLocale(locale, DEFAULT_LOCALE);
  const row = table[key];
  const text = row[lang] ?? row[DEFAULT_LOCALE] ?? row.en;
  return interpolate(text, vars);
}

export function validateI18n(): string[] {
  const errors: string[] = [];
  const keys = Object.keys(table) as MessageKey[];
  const seen = new Set<string>();
  for (const key of keys) {
    if (seen.has(key)) errors.push(`duplicate key ${key}`);
    seen.add(key);
    const row = table[key];
    for (const locale of LOCALES) {
      const value = row[locale];
      if (typeof value !== "string" || value.trim().length === 0) {
        errors.push(`missing ${locale} for ${key}`);
      }
    }
  }
  return errors;
}

